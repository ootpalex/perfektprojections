"""
TGS Projections Data Extractor — Multi-League
Auto-discovers all "The Sheets *" folders and extracts each league's data
into its own subfolder. Generates a leagues.json manifest for the web app.

Usage:
  python extract_data.py                 # Extract ALL leagues
  python extract_data.py BLM             # Extract only the "BLM" league
  python extract_data.py "BLM - Copy"    # Extract only "BLM - Copy"
  python extract_data.py --manifest-only # Rebuild leagues.json from the
                                         # existing public/data/<id>/ folders
                                         # (no workbook access, no data rewrite)

Manifest schema (public/data/leagues.json):
  {"leagues": [{"id", "name", "folder"?, "datasets": [...],
                "features": {"players": bool, "trends": bool,
                             "draft": bool, "fa": bool, "contracts": bool}}]}
Features are derived from what actually exists in public/data/<id>/:
  players   -> hitters.json / pitchers.json present (every player page)
  trends    -> rating_trends.json present (Rating Trends page)
  draft     -> hitters_draft.json / pitchers_draft.json present
  fa        -> hitters_fa.json / pitchers_fa.json present
  contracts -> any row in hitters/pitchers.json carries Price/ContractYrs/
               SalarySchedule (StatsPlus enrichment)
A TRENDS-ONLY league (players false, trends true) has no player files: the
app shows its Rating Trends page alone and lists it only while its
rating_trends.json exists. Example, the all-AI dev sim:
  {"id": "DEV", "name": "Dev test (all-AI sim)", "datasets": [],
   "features": {"players": false, "trends": true,
                "draft": false, "fa": false, "contracts": false}}
`--manifest-only` registers such a folder by itself (see TRENDS_ONLY_NAMES).
The manifest is MERGED on every run: leagues generated by other tools (e.g.
ingest/offline_league.py) are never dropped. The webapp also accepts the
legacy bare-array schema and falls back to built-in TGS/BLM if the manifest
is missing entirely.
"""

import json
import os
import sys
from datetime import datetime
from openpyxl import load_workbook

# Parent directory containing all "The Sheets *" folders.
# Resolves to the folder that contains tgs-viz/ — i.e. the repo root —
# regardless of where this script is run from or where the repo lives on disk.
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PARENT_DIR = os.path.dirname(SCRIPT_DIR)
OUTPUT_BASE = os.path.join(SCRIPT_DIR, "public", "data")

# The 4 Excel files we look for in each league folder.
# Keys = dataset name, values = (possible filenames, output json name, sheet hint)
# Filenames are checked case-insensitively.
DATASET_DEFS = {
    "hitters": {
        "filenames": ["The Sheet Hitters.xlsx"],
        "output": "hitters.json",
        "sheet_hint": "Hitters",
    },
    "pitchers": {
        "filenames": ["The Sheet Pitchers.xlsx"],
        "output": "pitchers.json",
        "sheet_hint": "Pitchers",
    },
    "hitters_draft": {
        "filenames": ["The Sheet Hitters - Draft.xlsx"],
        "output": "hitters_draft.json",
        "sheet_hint": "Hitters",
    },
    "pitchers_draft": {
        "filenames": ["The Sheet Pitchers - Draft.xlsx", "The Sheet Pitchers - DRAFT.xlsx"],
        "output": "pitchers_draft.json",
        "sheet_hint": "Pitchers",
    },
    "hitters_fa": {
        "filenames": ["The Sheet Hitters - FA.xlsx"],
        "output": "hitters_fa.json",
        "sheet_hint": "Hitters",
    },
    "pitchers_fa": {
        "filenames": ["The Sheet Pitchers - FA.xlsx"],
        "output": "pitchers_fa.json",
        "sheet_hint": "Pitchers",
    },
}


def safe_val(val):
    """Convert Excel cell values to JSON-safe types."""
    if val is None:
        return None
    if isinstance(val, datetime):
        return val.strftime("%Y-%m-%d")
    if isinstance(val, (int, float)):
        if isinstance(val, float) and (val != val):  # NaN check
            return None
        return val
    return str(val).strip()


def extract_sheet(filepath, sheet_name, max_rows=None):
    """Extract data from a specific sheet in an Excel file."""
    print(f"  Loading workbook: {os.path.basename(filepath)}...")
    wb = load_workbook(filepath, read_only=True, data_only=True)

    # Find the right sheet (case-insensitive exact match first)
    target_sheet = None
    for name in wb.sheetnames:
        if name.lower() == sheet_name.lower():
            target_sheet = name
            break

    if not target_sheet:
        # Try partial match
        for name in wb.sheetnames:
            if sheet_name.lower() in name.lower():
                target_sheet = name
                break

    if not target_sheet:
        print(f"  Available sheets: {wb.sheetnames}")
        print(f"  WARNING: Sheet '{sheet_name}' not found!")
        wb.close()
        return []

    print(f"  Reading sheet: {target_sheet}")
    ws = wb[target_sheet]

    rows = []
    headers = None
    row_count = 0

    for row in ws.iter_rows():
        values = [safe_val(cell.value) for cell in row]

        if headers is None:
            headers = values
            headers = [str(h).strip() if h else f"Col_{i}" for i, h in enumerate(headers)]
            continue

        if all(v is None for v in values):
            continue

        record = {}
        for i, h in enumerate(headers):
            if i < len(values):
                record[h] = values[i]
            else:
                record[h] = None

        rows.append(record)
        row_count += 1

        if max_rows and row_count >= max_rows:
            break

        if row_count % 1000 == 0:
            print(f"    Processed {row_count} rows...")

    wb.close()
    print(f"  Extracted {row_count} rows with {len(headers) if headers else 0} columns")
    return rows


def extract_draft_filter_ids(filepath):
    """Extract draft-eligible and already-drafted player IDs from a draft workbook.

    Reads two sheets:
      1. 'Player List' — rows with Manual='DRAFT' and a Name are draft-eligible.
      2. 'Drafted' — CSV-like rows pasted from StatsPlus with already-drafted IDs.

    Returns (eligible_ids, drafted_ids, dem_map, pitch_map) where pitch_map is
    a dict of player ID -> {FB, FBP, CH, CHP, ...} pitch rating columns.
    """
    # Individual pitch type columns to extract from Player List
    PITCH_COLS = [
        'FB', 'FBP', 'CH', 'CHP', 'CB', 'CBP', 'SL', 'SLP',
        'SI', 'SIP', 'SP', 'SPP', 'CT', 'CTP', 'FO', 'FOP',
        'CC', 'CCP', 'SC', 'SCP', 'KC', 'KCP', 'KN', 'KNP',
    ]

    wb = load_workbook(filepath, read_only=True, data_only=True)

    # --- Player List: get draft-eligible IDs, DEM values, and pitch ratings ---
    eligible = set()
    dem_map = {}
    pitch_map = {}
    if 'Player List' in wb.sheetnames:
        ws = wb['Player List']
        headers = None
        for i, row in enumerate(ws.iter_rows()):
            vals = [cell.value for cell in row]
            if i == 0:
                headers = [str(v).strip() if v else f"Col_{j}" for j, v in enumerate(vals)]
                continue
            if not headers:
                continue
            rec = {headers[j]: vals[j] for j in range(min(len(headers), len(vals)))}

            pid = rec.get('ID')
            if pid is None:
                continue
            pid_str = str(pid).strip()

            # Draft eligibility: any player with a Name in the Player List is draft-eligible
            if rec.get('Name'):
                eligible.add(pid_str)

            # DEM value
            dem = rec.get('DEM')
            if dem is not None:
                dem_map[pid_str] = str(dem).strip()

            # Pitch ratings — store all available columns for this player
            pitch_data = {}
            for col in PITCH_COLS:
                v = rec.get(col)
                if v is not None:
                    pitch_data[col] = safe_val(v)
            if pitch_data:
                pitch_map[pid_str] = pitch_data

        print(f"  Player List: {len(eligible)} draft-eligible players with names")
        print(f"  Player List: {len(dem_map)} players with DEM values")
        print(f"  Player List: {len(pitch_map)} players with pitch ratings")

    # --- Drafted sheet: get already-drafted IDs ---
    drafted = set()
    if 'Drafted' in wb.sheetnames:
        ws = wb['Drafted']
        for i, row in enumerate(ws.iter_rows()):
            if i == 0:
                continue  # skip header
            val = row[0].value
            if val and isinstance(val, str) and val.startswith('"'):
                parts = val.replace('"', '').split(',')
                if parts[0].strip():
                    drafted.add(parts[0].strip())
        print(f"  Drafted sheet: {len(drafted)} already-drafted player IDs")

    remaining = eligible - drafted
    print(f"  Remaining draftable: {len(remaining)}")

    wb.close()
    return eligible, drafted, dem_map, pitch_map


def extract_sheet_names(filepath):
    """Get all sheet names from a workbook."""
    wb = load_workbook(filepath, read_only=True)
    names = wb.sheetnames
    wb.close()
    return names


def find_file_case_insensitive(directory, possible_names):
    """Find a file in directory matching any of the possible names (case-insensitive)."""
    try:
        actual_files = os.listdir(directory)
    except OSError:
        return None

    # Build a lowercase lookup
    lower_map = {f.lower(): f for f in actual_files}

    for name in possible_names:
        actual = lower_map.get(name.lower())
        if actual:
            return os.path.join(directory, actual)

    return None


def discover_leagues():
    """Find all 'The Sheets *' folders in the parent directory."""
    leagues = []
    try:
        entries = os.listdir(PARENT_DIR)
    except OSError as e:
        print(f"ERROR: Cannot read parent directory: {e}")
        return leagues

    for entry in sorted(entries):
        full_path = os.path.join(PARENT_DIR, entry)
        if os.path.isdir(full_path) and entry.startswith("The Sheets"):
            # Derive league ID: "The Sheets BLM" -> "BLM", "The Sheets TGS - Copy" -> "TGS - Copy"
            league_id = entry.replace("The Sheets", "").strip()
            if not league_id:
                league_id = "Default"
            leagues.append({
                "id": league_id,
                "name": league_id,
                "folder": entry,
                "path": full_path,
            })

    return leagues


# ─── leagues.json manifest helpers ──────────────────────────────────────────
# Shared by this extractor and ingest/offline_league.py (which imports them).

# Presence of any of these keys on a player row means the league carries
# StatsPlus contract enrichment (Market Value / contract columns are usable).
CONTRACT_KEYS = ("Price", "ContractYrs", "SalarySchedule")


def detect_league_datasets(league_dir):
    """Dataset keys whose output JSON actually exists in public/data/<id>/."""
    return [k for k, d in DATASET_DEFS.items()
            if os.path.exists(os.path.join(league_dir, d["output"]))]


def detect_league_features(league_dir):
    """Derive the app's per-league feature flags from the files on disk."""
    def has(name):
        return os.path.exists(os.path.join(league_dir, name))

    features = {
        "players": has("hitters.json") or has("pitchers.json"),
        "trends": has("rating_trends.json"),
        "draft": has("hitters_draft.json") or has("pitchers_draft.json"),
        "fa": has("hitters_fa.json") or has("pitchers_fa.json"),
        "contracts": False,
    }
    for fname in ("hitters.json", "pitchers.json"):
        fp = os.path.join(league_dir, fname)
        if not os.path.exists(fp):
            continue
        try:
            with open(fp, encoding="utf-8") as f:
                rows = json.load(f)
        except (OSError, ValueError):
            continue
        if any(k in row for row in rows for k in CONTRACT_KEYS):
            features["contracts"] = True
            break
    return features


def load_manifest_entries(manifest_path):
    """Read leagues.json in either schema; return a list of league entries.
    New schema: {"leagues": [...]}. Legacy schema: bare [...]."""
    try:
        with open(manifest_path, encoding="utf-8") as f:
            raw = json.load(f)
    except (OSError, ValueError):
        return []
    if isinstance(raw, dict):
        raw = raw.get("leagues", [])
    if not isinstance(raw, list):
        return []
    return [e for e in raw if isinstance(e, dict) and e.get("id")]


def upsert_manifest(manifest_path, new_entries):
    """Merge new/updated league entries into leagues.json (keyed by id) and
    write the new {"leagues": [...]} schema. Entries not in new_entries are
    preserved so leagues from other pipelines are never dropped."""
    by_id = {e["id"]: e for e in load_manifest_entries(manifest_path)}
    for entry in new_entries:
        merged = dict(by_id.get(entry["id"], {}))
        merged.update(entry)
        by_id[entry["id"]] = merged
    entries = sorted(by_id.values(), key=lambda x: x["id"])
    with open(manifest_path, 'w', encoding='utf-8') as f:
        json.dump({"leagues": entries}, f, indent=2, ensure_ascii=False)
    return entries


# Display names for trends-only leagues that --manifest-only registers from a
# public/data/<id>/ folder holding rating_trends.json but no player files.
# DEV = the all-AI OOTP 27 sim ("DEV TESTS.lg"), fed once a year by its dump.
# TODO(DEV): the DEV trends export can register itself instead with
#   extract_data.upsert_manifest(path, [extract_data.build_manifest_entry("DEV", name=...)])
TRENDS_ONLY_NAMES = {"DEV": "Dev test (all-AI sim)"}


def discover_trends_only(known_ids):
    """Trends-only league folders under public/data/ that the manifest lacks."""
    found = []
    try:
        entries = sorted(os.listdir(OUTPUT_BASE))
    except OSError:
        return found
    for entry in entries:
        league_dir = os.path.join(OUTPUT_BASE, entry)
        if entry in known_ids or not os.path.isdir(league_dir):
            continue
        feats = detect_league_features(league_dir)
        if feats["trends"] and not feats["players"]:
            found.append({"id": entry, "name": TRENDS_ONLY_NAMES.get(entry, entry)})
    return found


def build_manifest_entry(league_id, name=None, folder=None):
    """Build one manifest entry by inspecting the league's output folder."""
    league_dir = os.path.join(OUTPUT_BASE, league_id)
    entry = {
        "id": league_id,
        "name": name or league_id,
        "datasets": detect_league_datasets(league_dir),
        "features": detect_league_features(league_dir),
    }
    if folder:
        entry["folder"] = folder
    return entry


def read_matchups(hitters_filepath):
    """Read the platoon split shares from the hitters workbook's Data Points sheet
    (Matchups block: LvR / RvR / SvR / OVR vR — fraction of PA each batter type faces
    vs RHP). "OVR vR" is the season-overall vs-RHP share the roster optimizer weights
    the two platoon lineups by. Returns a dict like {"OVR vR": 0.7368, ...} or None.
    """
    want = {"LvR", "RvR", "SvR", "OVR vR"}
    try:
        wb = load_workbook(hitters_filepath, read_only=True, data_only=True)
        ws = next((wb[n] for n in wb.sheetnames
                   if "data" in n.lower() and "point" in n.lower()), None)
        if ws is None:
            wb.close()
            return None
        out = {}
        for row in ws.iter_rows(min_row=1, max_row=60):
            for i, c in enumerate(row):
                if isinstance(c.value, str) and c.value.strip() in want and i + 1 < len(row):
                    rv = row[i + 1].value
                    if isinstance(rv, (int, float)):
                        out[c.value.strip()] = float(rv)
        wb.close()
        return out or None
    except Exception as e:
        print(f"  WARNING: could not read matchup shares: {e}")
        return None


def extract_league(league, output_base):
    """Extract all datasets for a single league."""
    league_id = league["id"]
    league_path = league["path"]
    league_output = os.path.join(output_base, league_id)
    os.makedirs(league_output, exist_ok=True)

    print(f"\n{'='*60}")
    print(f"LEAGUE: {league_id}")
    print(f"Source: {league_path}")
    print(f"Output: {league_output}")
    print(f"{'='*60}")

    extracted_datasets = []
    all_data = {}

    for ds_key, ds_def in DATASET_DEFS.items():
        filepath = find_file_case_insensitive(league_path, ds_def["filenames"])

        if not filepath:
            print(f"\n  [{ds_key}] No matching file found (looked for: {ds_def['filenames']})")
            continue

        print(f"\n  [{ds_key}] Found: {os.path.basename(filepath)}")

        sheets = extract_sheet_names(filepath)
        print(f"  Sheets: {sheets}")

        data = extract_sheet(filepath, ds_def["sheet_hint"])

        if not data and len(sheets) >= 5:
            print(f"  Trying sheet by index: {sheets[4]}")
            data = extract_sheet(filepath, sheets[4])

        # For draft datasets, filter to only draft-eligible players
        # who haven't been drafted yet (using Player List + Drafted sheets)
        is_draft = ds_key in ("hitters_draft", "pitchers_draft")
        if data and is_draft:
            eligible, drafted, dem_map, pitch_map = extract_draft_filter_ids(filepath)
            draftable = eligible - drafted
            if draftable:
                before = len(data)
                data = [row for row in data if str(row.get("ID", "")).strip() in draftable]
                print(f"  Draft filter: {before} -> {len(data)} players (removed {before - len(data)} non-draftable)")
            else:
                print(f"  WARNING: No draftable IDs found — keeping all data unfiltered")

            # Attach DEM (demand) values from Player List to each player
            if dem_map:
                dem_count = 0
                for row in data:
                    pid = str(row.get("ID", "")).strip()
                    row["DEM"] = dem_map.get(pid, None)
                    if row["DEM"]:
                        dem_count += 1
                print(f"  DEM values attached: {dem_count} players")

            # Attach individual pitch ratings from Player List (pitchers only)
            if pitch_map and ds_key == "pitchers_draft":
                pitch_count = 0
                for row in data:
                    pid = str(row.get("ID", "")).strip()
                    pdata = pitch_map.get(pid)
                    if pdata:
                        row.update(pdata)
                        pitch_count += 1
                print(f"  Pitch ratings merged: {pitch_count} pitchers")

        if data:
            outpath = os.path.join(league_output, ds_def["output"])
            with open(outpath, 'w', encoding='utf-8') as f:
                json.dump(data, f, ensure_ascii=False)
            size_mb = os.path.getsize(outpath) / (1024 * 1024)
            print(f"  Saved {len(data)} records to {ds_def['output']} ({size_mb:.1f} MB)")
            extracted_datasets.append(ds_key)
            all_data[ds_key] = data
        else:
            print(f"  ERROR: No data extracted for {ds_key}!")

    # Per-league metadata
    meta = {
        "extracted_at": datetime.now().isoformat(),
        "league": league_id,
        "source_dir": league_path,
        "datasets": {}
    }
    for key, data in all_data.items():
        if data:
            meta["datasets"][key] = {
                "count": len(data),
                "columns": list(data[0].keys()) if data else [],
                "sample": data[0] if data else None
            }

    # Platoon matchup shares (vR/vL season split) — used by the roster optimizer.
    hitters_fp = find_file_case_insensitive(league_path, DATASET_DEFS["hitters"]["filenames"])
    if hitters_fp:
        mu = read_matchups(hitters_fp)
        if mu:
            meta["matchups"] = mu
            print(f"  Matchups: {mu}")

    meta_path = os.path.join(league_output, "metadata.json")
    with open(meta_path, 'w', encoding='utf-8') as f:
        json.dump(meta, f, indent=2, ensure_ascii=False)

    return extracted_datasets


def refresh_manifest_only():
    """Rebuild leagues.json from the existing public/data/<id>/ folders without
    opening any workbook or rewriting any data JSON. Refreshes datasets/features
    of every league already in the manifest (upgrading legacy-schema files in
    place). New player leagues are added by their generators (a full extract
    run, or ingest/offline_league.py --write); a new trends-only folder
    (rating_trends.json, no player files) is registered here."""
    manifest_path = os.path.join(OUTPUT_BASE, "leagues.json")
    existing = load_manifest_entries(manifest_path)
    if not existing:
        # No manifest yet: bootstrap from the sheet folders that have output dirs.
        existing = [{"id": lg["id"], "name": lg["name"], "folder": lg["folder"]}
                    for lg in discover_leagues()
                    if os.path.isdir(os.path.join(OUTPUT_BASE, lg["id"]))]
    existing += discover_trends_only({e["id"] for e in existing})
    refreshed = [build_manifest_entry(e["id"], name=e.get("name"), folder=e.get("folder"))
                 for e in existing]
    entries = upsert_manifest(manifest_path, refreshed)
    print(f"Manifest refreshed ({manifest_path}):")
    for lg in entries:
        feats = ", ".join(k for k, v in (lg.get("features") or {}).items() if v) or "none"
        print(f"  {lg['id']}: datasets=[{', '.join(lg.get('datasets', []))}] features=[{feats}]")


def main():
    print("TGS Projections Data Extractor — Multi-League")
    print(f"Parent: {PARENT_DIR}")
    print(f"Output: {OUTPUT_BASE}")

    os.makedirs(OUTPUT_BASE, exist_ok=True)

    if "--manifest-only" in sys.argv[1:]:
        refresh_manifest_only()
        return

    # Discover all league folders
    leagues = discover_leagues()

    if not leagues:
        print("\nERROR: No 'The Sheets *' folders found!")
        sys.exit(1)

    print(f"\nDiscovered {len(leagues)} league(s):")
    for lg in leagues:
        print(f"  - {lg['id']} ({lg['folder']})")

    # Optional: filter to a single league if CLI arg provided
    filter_league = None
    if len(sys.argv) > 1:
        filter_league = sys.argv[1]
        matching = [lg for lg in leagues if lg["id"] == filter_league]
        if not matching:
            print(f"\nERROR: League '{filter_league}' not found!")
            print(f"Available: {[lg['id'] for lg in leagues]}")
            sys.exit(1)
        leagues = matching
        print(f"\nFiltering to league: {filter_league}")

    # Extract each league, then build its manifest entry from what actually
    # landed on disk (datasets + feature flags).
    updated_entries = []
    for league in leagues:
        extract_league(league, OUTPUT_BASE)
        updated_entries.append(
            build_manifest_entry(league["id"], name=league["name"], folder=league["folder"])
        )

    # Merge into the manifest. ALWAYS a merge (not a rewrite) so leagues
    # produced by other pipelines (offline_league.py) survive a full run.
    manifest_path = os.path.join(OUTPUT_BASE, "leagues.json")
    league_manifest = upsert_manifest(manifest_path, updated_entries)

    print(f"\n{'='*60}")
    print("EXTRACTION COMPLETE")
    print(f"{'='*60}")
    print(f"\nLeagues manifest ({manifest_path}):")
    for lg in league_manifest:
        ds_list = ", ".join(lg.get("datasets", [])) or "none"
        feats = ", ".join(k for k, v in (lg.get("features") or {}).items() if v) or "none"
        print(f"  {lg['id']}: [{ds_list}] features=[{feats}]")

    print(f"\nTotal leagues: {len(league_manifest)}")


if __name__ == "__main__":
    main()
